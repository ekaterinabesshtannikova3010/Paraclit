from django.shortcuts import render
from django.http import JsonResponse
from django.core.mail import send_mail
from django.views.decorators.http import require_POST
from django.conf import settings


@require_POST
def feedback_submit(request):
    name = request.POST.get('name', '').strip()
    email = request.POST.get('email', '').strip()
    subject = request.POST.get('subject', '').strip()
    message = request.POST.get('message', '').strip()

    # Простая валидация
    if not (name and email and subject and message):
        return JsonResponse({'success': False, 'error': 'Пожалуйста заполните все поля.'})

    full_message = f"Сообщение от {name} <{email}>\n\n{message}"

    try:
        # Пример отправки письма на указанный email или в консоль/админ
        send_mail(
            subject=f"[Обращение] {subject}",
            message=full_message,
            from_email=settings.DEFAULT_FROM_EMAIL,
            recipient_list=[settings.CONTACT_RECIPIENT_EMAIL],
            fail_silently=False,
        )
        return JsonResponse({'success': True})
    except Exception as e:
        # Логирование можно добавить
        print(str(e))
        return JsonResponse({'success': False, 'error': str(e)})
